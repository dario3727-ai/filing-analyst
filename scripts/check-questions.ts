// npm run check:questions [-- --model haiku]
// Milestone 3 check: runs the 10 hand-written questions through the same
// pipeline as POST /api/ask (Sonnet by default), saves each answer, and
// writes docs/checks/milestone-3-questions.md for review.
// At most 10 Voyage + 10 Claude requests (~$0.20 on Sonnet).
import { mkdirSync, writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import { MILESTONE3_QUESTIONS } from "../src/config/milestone3-questions.ts";
import { DEV_MODEL, QA_MODEL } from "../src/lib/qa/answer.ts";
import { handleAsk, type AskResponse } from "../src/lib/qa/ask.ts";
import { createAskDepsFromEnv } from "../src/lib/qa/server-deps.ts";

const MAX_QUESTIONS = 15;
const { values } = parseArgs({ options: { model: { type: "string" } } });
const model = values.model === "haiku" ? DEV_MODEL : QA_MODEL;
if (MILESTONE3_QUESTIONS.length > MAX_QUESTIONS) throw new Error(`More than ${MAX_QUESTIONS} questions; raise the cap deliberately.`);

// Fresh answers every run: reusing stored ones would hide any change to search or prompts.
const built = createAskDepsFromEnv(process.env, { model, voyageMaxRequests: MILESTONE3_QUESTIONS.length + 2, reuseAnswers: false });
if (!built.ok) throw new Error(`Missing ${built.missing.join(", ")} (run npm run check:env)`);
const { deps } = built;

const lines: string[] = [];
const summary: string[] = [];
let matched = 0;

console.log(`Running ${MILESTONE3_QUESTIONS.length} questions on ${model}...\n`);
for (const q of MILESTONE3_QUESTIONS) {
  const result = await handleAsk({ ticker: q.ticker, question: q.question, fromYear: q.fromYear, toYear: q.toYear }, deps);
  if (!result.ok) {
    summary.push(`| ${q.id} | ${q.expect} | error ${result.status} | | |`);
    lines.push(`## ${q.id}: ${q.question}\n\n**Error ${result.status}:** ${result.error}\n`);
    console.log(`  ${q.id.padEnd(22)} ERROR ${result.status}: ${result.error}`);
    continue;
  }
  const r: AskResponse = result.response;
  // "partly answered" counts as answered for an answerable question.
  const outcome = r.status === "partly_answered" ? "answered" : r.status;
  const ok = outcome === q.expect;
  if (ok) matched++;
  const n = r.numbers;
  summary.push(
    `| ${q.id} | ${q.expect} | ${r.status}${ok ? "" : " ✗"} | ${r.sources.length} | ${n.total} found: ${n.xbrl} XBRL, ${n.passage} text, ${n.unverified} unverified |`,
  );
  console.log(
    `  ${q.id.padEnd(22)} ${r.status.padEnd(16)} ${ok ? "as expected" : `EXPECTED ${q.expect}`}  ` +
      `${r.sources.length} sources, numbers ${n.xbrl}/${n.passage}/${n.unverified}${r.cached ? " (reused)" : ""}`,
  );

  const body = r.segments.map((s) => s.text + (s.sources.length ? ` [${s.sources.join(", ")}]` : "")).join("").trim();
  lines.push(
    `## ${q.id}: ${q.question}`,
    "",
    `${q.ticker}, fiscal ${q.fromYear === q.toYear ? q.fromYear : `${q.fromYear}–${q.toYear}`} · expected **${q.expect}** · got **${r.status}** · answer #${r.answerId}${r.cached ? " (reused)" : ""}`,
    "",
    `*Look for:* ${q.lookFor}`,
    "",
    body
      .split("\n")
      .map((l) => `> ${l}`)
      .join("\n"),
    "",
    ...(r.sources.length ? ["**Sources**", ""] : []),
    ...r.sources.map(
      (s) =>
        `${s.n}. FY${s.fiscalYear} Item ${s.item}${s.heading ? ` · ${s.heading}` : ""}, p. ${s.pageStart}${s.pageEnd !== s.pageStart ? `–${s.pageEnd}` : ""} (passage ${s.passageId}): "${s.citedText.replace(/\s+/g, " ").slice(0, 300)}${s.citedText.length > 300 ? "…" : ""}"`,
    ),
    "",
    `**Numbers:** ${n.total} found · ${n.xbrl} match XBRL · ${n.passage} in the filing text · ${n.unverified} unverified`,
    ...n.figures.map(
      (f) =>
        `- ${f.raw}: ${f.status === "xbrl" ? `XBRL ${f.concept} (FY${f.fiscalYear})` : f.status === "passage" ? "in the filing text" : "**unverified**"}${f.xbrlCandidates ? ` (value shared by ${f.xbrlCandidates} XBRL items)` : ""}`,
    ),
    "",
  );
}

const report = [
  "# Milestone 3 check: 10 hand-written questions",
  "",
  `Generated by \`npm run check:questions\` on ${new Date().toISOString().slice(0, 10)} with \`${model}\`. Questions and what to look for: \`src/config/milestone3-questions.ts\`.`,
  "",
  `**${matched} of ${MILESTONE3_QUESTIONS.length}** gave the expected kind of response (answered, or said the filing doesn't say). Correctness of each answer is reviewed below against its cited passages.`,
  "",
  "| Question | Expected | Got | Sources | Numbers |",
  "| --- | --- | --- | --- | --- |",
  ...summary,
  "",
  ...lines,
].join("\n");

mkdirSync("docs/checks", { recursive: true });
writeFileSync("docs/checks/milestone-3-questions.md", report);
console.log(`\n${matched}/${MILESTONE3_QUESTIONS.length} as expected. Report: docs/checks/milestone-3-questions.md`);
